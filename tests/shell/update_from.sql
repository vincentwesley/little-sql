-- UPDATE ... FROM (joins, subqueries, aliases, WITHOUT ROWID, triggers) and WITH before UPDATE / DELETE.
create table inv(item text primary key, qty int);
insert into inv values('a', 1), ('b', 2), ('c', 3);
create table sales(item text, n int);
insert into sales values('a', 5), ('a', 7), ('b', 1), ('z', 9);
update inv set qty = qty + sales.n from sales where sales.item = inv.item;
select * from inv;
update inv set qty = qty - s.total from (select item, sum(n) as total from sales group by item) as s where s.item = inv.item returning inv.item, qty;
update inv set qty = 0 from sales;
select * from inv;
update inv as i set qty = i.qty + 1 from sales s where s.item = i.item and s.n > 4;
select * from inv;
update inv set qty = sales.n from sales, sales as s2 where sales.item = inv.item and s2.item = 'z';
select * from inv;
update inv set qty = 9 from inv as other where other.item = inv.item;
select * from inv;
update inv set qty = x from (values(42)) as v(x);
create table wr(k text primary key, v int) without rowid;
insert into wr values('a', 1), ('b', 2);
update wr set v = v * 100 + sales.n from sales where sales.item = wr.k;
select * from wr;
create table hist(m);
create trigger th after update on inv begin insert into hist values(old.item || ':' || old.qty || '->' || new.qty); end;
update inv set qty = sales.n from sales where sales.item = inv.item and sales.n < 6;
select * from hist;
with big as (select item, max(n) as m from sales group by item) update inv set qty = big.m from big where big.item = inv.item;
select * from inv;
update inv set qty = -1 from sales left join wr on wr.k = sales.item where sales.item = inv.item and wr.k is null;
select * from inv;
update inv set nosuch = 1 from sales;
update inv set qty = sales.nosuch from sales;
