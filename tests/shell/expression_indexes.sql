insert into p values(5, 'd@x.com', 'Dee', 1, 4.5);
update p set email = 'B@X.com' where id = 5;
update p set active = 0 where id = 1;
insert into p values(6, 'a@x.com', 'again', 1, 0);
insert or replace into p values(7, 'C@X.COM', 'cy2', 0, 9);
select * from p order by id;
delete from p where id = 2;
select count(*) from p;
create index bad1 on p(random());
create index bad2 on p(name) where id in (select 1);
create index bad3 on p(nosuch + 1);
create index p_price on p(price * 2) where price > 2;
