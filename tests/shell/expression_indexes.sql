-- Expression and partial indexes: kept up to date by INSERT / UPDATE / DELETE / REPLACE, uniqueness through them, and the restrictions on their expressions.
create table p(id integer primary key, email text, name text, active int, price real);
create unique index p_email on p(lower(email));
create index p_name_len on p(length(name), name collate nocase desc);
create index p_active on p(name) where active = 1;
create unique index p_one_active on p(email) where active = 1;
insert into p values(1, 'A@x.com', 'Ann', 1, 1.5), (2, 'b@x.com', 'bob', 0, 2.5), (3, 'c@x.com', 'Cy', 1, 3.5);
